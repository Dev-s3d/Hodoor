<?php

require_once '../../config/bootstrap.php';

/*
|--------------------------------------------------------------------------
| حذف بيانات المستخدم الحالية
|--------------------------------------------------------------------------
*/

clsHelper::clearAuth();

clsHelper::sessionRemove('old');
clsHelper::sessionRemove('filters');

/*
|--------------------------------------------------------------------------
| تدمير الجلسة الحالية
|--------------------------------------------------------------------------
*/

session_destroy();

/*
|--------------------------------------------------------------------------
| إنشاء جلسة جديدة للحماية
|--------------------------------------------------------------------------
*/

session_start();
session_regenerate_id(true);

/*
|--------------------------------------------------------------------------
| رسالة نجاح
|--------------------------------------------------------------------------
*/

clsHelper::setMessage(
    'success',
    'تم تسجيل الخروج بنجاح'
);

/*
|--------------------------------------------------------------------------
| إعادة التوجيه
|--------------------------------------------------------------------------
*/

clsHelper::redirect(
    clsPath::login()
);